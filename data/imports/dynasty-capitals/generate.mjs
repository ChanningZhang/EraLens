/** @param {object} input */
function capital({
  id,
  dynastyId,
  historicalName,
  modernName,
  longitude,
  latitude,
  start,
  end,
  precision = "year",
  role = "primary",
  claimTrack,
  note,
  wikiTitle,
  startDateConfidence,
  endDateConfidence,
}) {
  return {
    id,
    dynastyId,
    historicalName,
    modernName,
    longitude,
    latitude,
    coordinateSystem: "GCJ02",
    start,
    end,
    startAbs: start.abs ?? absMonth(start.year, start.month),
    endAbs: end.abs ?? absMonth(end.year, end.month),
    precision,
    role,
    claimTrack,
    note,
    startDateConfidence,
    endDateConfidence,
    links: wikiTitle ? wiki(wikiTitle) : [],
  };
}

